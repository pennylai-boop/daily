/**
 * 隨機抽一則，`exclude` 是上一則，避免連續兩次抽到同一句。
 * 真的很不巧連抽到同一句時就往後移一格，不用 while 迴圈賭運氣。
 */
export function randomPepTalk(exclude?: string | null): string {
  const index = Math.floor(Math.random() * PEP_TALKS.length);
  const picked = PEP_TALKS[index];
  if (picked !== exclude) return picked;
  return PEP_TALKS[(index + 1) % PEP_TALKS.length];
}
